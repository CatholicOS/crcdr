#!/usr/bin/env python3
"""Generate registry/bodies.md, registry/lineages.md and data/identifiers.json.

The outputs are generated, never hand-edited. Refuses to write if the data has
validation errors. Output is deterministic (no timestamps).

Usage:  python3 -I scripts/generate_registry.py
"""
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import crcdr  # noqa: E402
import validate  # noqa: E402

OUT_DIR = os.path.join(crcdr.ROOT, "registry")
IDS_PATH = os.path.join(crcdr.ROOT, "data", "identifiers.json")
CURRENT_REGIME = "praedicate-evangelium-2022"
MARK = "†"
GAP_MARK = "‡"

COMMENT = ("CC0 1.0 (see LICENSE-CC0). Generated by scripts/generate_registry.py "
           "from data/bodies.json and data/events.json; never hand-edited. Lookup is by "
           "(name, date): a string in `names` (the body's own Latin and English names) or "
           "`aliases` (other attested forms) denotes the entry's id only on dates in its "
           "[from, to) interval (`to` exclusive, null = still open; ISO 8601 at the "
           "precision known, a partial date comparing as its first day).")


def load_data():
    return crcdr.load("bodies"), crcdr.load("events")


def _cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def _marks(fact):
    """The markers a fact earns: † unverified, ‡ carries a documented gap."""
    if not fact:
        return ""
    return "".join((MARK if fact.get("verified") is False else "",
                    GAP_MARK if fact.get("gap") else ""))


def _mark(text, fact):
    if text in (None, ""):
        return ""
    m = _marks(fact)
    return f"{text} {m}" if m else str(text)


def _index(bodies):
    return {b["id"]: b for b in bodies["entries"]}


def _effects(vocab):
    return {t["id"]: t["effect"] for t in vocab["event_types"]["entries"]}


def _links(bodies, events, effects):
    """(predecessor, successor, event) triples derived from events by effect."""
    out = []
    for ev in events["entries"]:
        eff = effects.get(ev["event_type"])
        sb, sa = set(ev.get("before") or []), set(ev.get("after") or [])
        if eff in ("new", "absorb"):
            for p in sorted(sb - sa):
                for s in sorted(sa - sb if eff == "new" else sa):
                    out.append((p, s, ev))
    return out


def _default_effects():
    return _effects({"event_types": crcdr.load("event_types")})


def _dated(out, name, lang, frm, to):
    """Append {name, lang, from, to}, extending an entry for the same name that
    ends where this one starts (a name kept across a rename of the other language)."""
    for x in out:
        if (x["name"], x["lang"]) == (name, lang) and x["to"] == frm and frm is not None:
            x["to"] = to
            return
    out.append({"name": name, "lang": lang, "from": frm, "to": to})


def identifiers(bodies, events, effects=None):
    effects = effects or _default_effects()
    pred, succ = {}, {}
    for p, s, _ev in _links(bodies, events, effects):
        succ.setdefault(p, set()).add(s)
        pred.setdefault(s, set()).add(p)
    entries = []
    for b in sorted(bodies["entries"], key=lambda x: x["id"]):
        names, aliases = [], []
        for n in b.get("names") or []:
            for k, lang in (("name_la", "la"), ("name_en", "en")):
                if n.get(k):
                    _dated(names, n[k], lang, n.get("from"), n.get("to"))
            for a in n.get("aliases") or []:
                _dated(aliases, a["name"], a["lang"], n.get("from"), n.get("to"))
        ended = b.get("ended")
        for a in b.get("aliases") or []:
            _dated(aliases, a["name"], a["lang"], b["founded"]["date"],
                   ended["date"] if ended else None)
        entries.append({
            "id": b["id"],
            "names": names,
            "aliases": aliases,
            "predecessors": sorted(pred.get(b["id"], ())),
            "successors": sorted(succ.get(b["id"], ())),
            "founding_act_mag": None,
        })
    return {"$comment": COMMENT, "license": "CC0-1.0", "entries": entries}


def _name_at(b, today):
    names = b.get("names") or []
    return (None if b.get("ended") else crcdr.at(names, today)) or (names[-1] if names else {})


def _display(b, today):
    n = _name_at(b, today)
    la = _mark(n.get("name_la") or n.get("name_en") or "", n)
    en = _mark(n.get("name_en"), n) if n.get("name_la") else ""
    return la, en


def _kind(b, today):
    ks = b.get("kind") or []
    k = (None if b.get("ended") else crcdr.at(ks, today)) or (ks[-1] if ks else None)
    return _mark(k["kind"], k) if k else ""


def _fact(f):
    if not f:
        return ""
    s = _mark(f.get("date"), f)
    if f.get("act"):
        s += f" ({f['act']})"
    return s


def _section_label(regime, sid):
    for s in regime["sections"]:
        if s["id"] == sid:
            return s["la"] or s["en"] or sid
    return sid


HEADER = """# Bodies of the Roman Curia

{count} canonical draft IDs for bodies of the Roman Curia ({living} living, {ended}
ended), in the form `cr:<latin-slug>-<founding-year>`. Living bodies are grouped by
the section the *Praedicate Evangelium* regime places them in today, in the order that
constitution lists its sections; ended bodies are grouped by the regime in force when
they ended. **Name** is the current (or last) Latin name, then the English name where
one is recorded; **Kind** is the current (or last) kind; **Founded** and **Ended** give
the date and the act. The history of each body (renames, mergers, splits) is in
[`lineages.md`](lineages.md); the underlying facts, with provenance, are in
[`data/bodies.json`](../data/bodies.json) and [`data/events.json`](../data/events.json).

{mark} marks a fact (a name, date, kind or section) recorded with `verified: false`:
it comes from a secondary source or an act not yet read, and is unverified.
{gap_mark} marks a fact that carries a documented research gap (a `gap` note); on an ID it
marks a gap on the body as a whole. Every gap is quoted under [Known gaps](#known-gaps).

All IDs are drafts pending CETF review. The *Annuario Pontificio* has not been
consulted. Authority over the documents of these bodies belongs to CMDDR, not here.
"""

COLS = "| ID | Name (Latin) | Name (English) | Kind | Section | Founded | Ended |\n|---|---|---|---|---|---|---|\n"


def _row(b, today, sec):
    la, en = _display(b, today)
    ident = f"`{b['id']}`" + (f" {GAP_MARK}" if b.get("gap") else "")
    cells = [ident, la, en, _kind(b, today), sec, _fact(b["founded"]), _fact(b.get("ended"))]
    return "| " + " | ".join(_cell(c) for c in cells) + " |\n"


def _gaps(warnings):
    if not warnings:
        return "No known gaps.\n"
    groups = {}
    for w in warnings:
        groups.setdefault(w.split("]", 1)[0] + "]", []).append(w)
    out = ["The validator reports these documented research gaps "
           f"({len(warnings)}), grouped by rule.\n"]
    for rule in sorted(groups, key=lambda r: int(r[2:-1])):
        out.append(f"\n### {rule[1:-1]} ({len(groups[rule])})\n\n")
        out.extend(f"- {w}\n" for w in groups[rule])
    return "".join(out)


def render_bodies(bodies, events, vocab, today=None):
    today = today or datetime.date.today().isoformat()
    sections = vocab["sections"]
    regimes = {r["id"]: r for r in sections["regimes"]}
    pe = regimes[CURRENT_REGIME]
    living = [b for b in bodies["entries"] if not b.get("ended")]
    ended = [b for b in bodies["entries"] if b.get("ended")]
    out = [HEADER.format(count=len(bodies["entries"]), living=len(living),
                         ended=len(ended), mark=MARK, gap_mark=GAP_MARK)]
    order = [s["id"] for s in pe["sections"]]
    groups = {}
    for b in living:
        cur = crcdr.at(b.get("section") or [], today)
        sid = cur["section"] if cur and cur["section"] in order else "not-listed"
        groups.setdefault(sid, []).append((b, cur))
    out.append("\n## Living bodies\n")
    for sid in order:
        if sid not in groups:
            continue
        sec = next(s for s in pe["sections"] if s["id"] == sid)
        title = " / ".join(x for x in (sec["la"], sec["en"]) if x) or sid
        out.append(f"\n### {title}\n\n{COLS}")
        for b, cur in sorted(groups[sid], key=lambda x: x[0]["id"]):
            out.append(_row(b, today, _mark(_section_label(pe, sid), cur)))
    out.append("\n## Ended bodies\n")
    by_regime = {}
    for b in ended:
        by_regime.setdefault(crcdr.regime_at(sections, b["ended"]["date"]), []).append(b)
    for r in sections["regimes"]:
        if r["id"] not in by_regime:
            continue
        out.append(f"\n### Ended under `{r['id']}`\n\n{COLS}")
        for b in sorted(by_regime[r["id"]], key=lambda x: (x["ended"]["date"], x["id"])):
            sl = crcdr.at(b.get("section") or [], b["ended"]["date"]) or (b.get("section") or [None])[-1]
            lab = _mark(_section_label(regimes.get(sl["regime"], r), sl["section"]), sl) if sl else ""
            out.append(_row(b, today, lab))
    rep = validate.validate(bodies, events, vocab)
    out.append("\n## Known gaps\n\n" + _gaps(rep.warnings))
    return "".join(out)


LHEADER = """# Lineages

One table per living body, tracing its history back through the events that made it:
renames and other same-identity changes, and the mergers, splits, absorptions and
re-foundations that link it to its predecessors. Predecessors and successors are
derived from events (a merger, split or re-foundation links each body that ceases to
each body that begins; an absorption links the absorbed body to the absorber). All IDs
are drafts pending CETF review; the *Annuario Pontificio* has not been consulted.
"""


def render_lineages(bodies, events, today=None):
    today = today or datetime.date.today().isoformat()
    idx = _index(bodies)
    effects = _default_effects()
    links = _links(bodies, events, effects)
    preds = {}
    for p, s, _ev in links:
        preds.setdefault(s, set()).add(p)
    out = [LHEADER]
    for b in sorted((x for x in bodies["entries"] if not x.get("ended")), key=lambda x: x["id"]):
        seen, todo = set(), [b["id"]]
        while todo:
            x = todo.pop()
            if x not in seen:
                seen.add(x)
                todo.extend(sorted(preds.get(x, ())))
        evs = sorted((e for e in events["entries"]
                      if seen & (set(e.get("before") or []) | set(e.get("after") or []))),
                     key=lambda e: (e["date"], e["id"]))
        la, _en = _display(b, today)
        out.append(f"\n## `{b['id']}` {la}\n\n")
        if not evs:
            out.append("No events recorded.\n")
            continue
        out.append("| Date | Event | Type | Act | Before | After |\n|---|---|---|---|---|---|\n")
        for e in evs:
            f = lambda ids: ", ".join(f"`{i}`" for i in (ids or [])) or "-"  # noqa: E731
            cells = [_mark(e["date"], e), e["id"], e["event_type"], e.get("act") or "",
                     f(e.get("before")), f(e.get("after"))]
            out.append("| " + " | ".join(_cell(c) for c in cells) + " |\n")
    return "".join(out)


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    bodies, events = load_data()
    vocab = validate.load_vocab()
    rep = validate.validate(bodies, events, vocab)
    if rep.errors:
        for e in rep.errors:
            print("ERROR " + e, file=sys.stderr)
        print(f"generate_registry: {len(rep.errors)} validation error(s); nothing written",
              file=sys.stderr)
        return 1
    today = datetime.date.today().isoformat()
    _write(os.path.join(OUT_DIR, "bodies.md"), render_bodies(bodies, events, vocab, today))
    _write(os.path.join(OUT_DIR, "lineages.md"), render_lineages(bodies, events, today))
    _write(IDS_PATH, json.dumps(identifiers(bodies, events), ensure_ascii=False, indent=2) + "\n")
    print(f"wrote {OUT_DIR}/bodies.md, lineages.md and {IDS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
